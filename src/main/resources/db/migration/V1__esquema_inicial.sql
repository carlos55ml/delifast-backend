    for select to authenticated using (cliente_id = (select auth.uid()));

-- Pedidos: el cliente los suyos; el negocio los de su negocio; el repartidor solo
-- los que el negocio le ha asignado (regla del 06-11-2026: el repartidor no elige
-- pedidos, así que no ve los LISTO pendientes de asignar); el admin todos.
-- Realtime aplica esta política: el panel del negocio escucha public.pedidos
-- filtrando por negocio_id.
create policy lectura_pedidos on public.pedidos
    for select to authenticated
    using (
        cliente_id = (select auth.uid())
        or (
            (select auth.jwt() ->> 'user_rol') = 'NEGOCIO'
            and negocio_id = (select (auth.jwt() ->> 'negocio_id')::bigint)
        )
        or (
            (select auth.jwt() ->> 'user_rol') = 'REPARTIDOR'
            and privado.reparto_es_mio(id)
        )
        or (select auth.jwt() ->> 'user_rol') = 'ADMINISTRADOR'
    );

-- Líneas e historial: los de los pedidos que el usuario puede ver
-- (la subconsulta pasa a su vez por la política de pedidos).
create policy lectura_pedidos on public.lineas_pedido
    for select to authenticated
    using (exists (select 1 from public.pedidos p where p.id = pedido_id));

create policy lectura_pedidos on public.cambios_estado
    for select to authenticated
    using (exists (select 1 from public.pedidos p where p.id = pedido_id));

-- Repartos: el repartidor los suyos; cliente y negocio los de sus pedidos
-- (el cliente sigue la posición en el mapa, RF-27).
create policy lectura_repartos on public.repartos
    for select to authenticated
    using (
        repartidor_id = (select auth.uid())
        or exists (select 1 from public.pedidos p where p.id = pedido_id)
    );

-- Incidencias: el autor, el negocio del pedido y el admin.
create policy lectura_incidencias on public.incidencias
    for select to authenticated
    using (
        autor_id = (select auth.uid())
        or (
            (select auth.jwt() ->> 'user_rol') = 'NEGOCIO'
            and exists (select 1 from public.pedidos p
                        where p.id = pedido_id
                          and p.negocio_id = (select (auth.jwt() ->> 'negocio_id')::bigint))
        )
        or (select auth.jwt() ->> 'user_rol') = 'ADMINISTRADOR'
    );


