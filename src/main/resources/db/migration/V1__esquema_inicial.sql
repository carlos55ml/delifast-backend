-- -----------------------------------------------------------------------------
-- 2. Alta automática del perfil
-- Cada usuario nuevo de auth.users recibe su fila en perfiles. Quien se registra
-- desde la app es CLIENTE. Las cuentas que crea el backend con la Admin API
-- (dueño, empleados, repartidores, admin) llevan rol y negocio en app_metadata,
-- que el usuario no puede modificar. El rol nunca se lee de user_metadata.
-- -----------------------------------------------------------------------------
create function public.crear_perfil()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.perfiles (id, nombre, email, telefono, rol, negocio_id, es_dueno)
    values (
        new.id,
        coalesce(nullif(trim(new.raw_user_meta_data ->> 'nombre'), ''), split_part(new.email, '@', 1)),
        new.email,
        new.raw_user_meta_data ->> 'telefono',
        coalesce(new.raw_app_meta_data ->> 'rol', 'CLIENTE'),
        (new.raw_app_meta_data ->> 'negocio_id')::bigint,
        coalesce((new.raw_app_meta_data ->> 'es_dueno')::boolean, false)
    );
    return new;
end;
$$;

revoke execute on function public.crear_perfil() from public, anon, authenticated;

create trigger al_crear_usuario
    after insert on auth.users
    for each row execute function public.crear_perfil();

-- La Admin API de Supabase Auth inserta el usuario con el app_metadata por defecto
-- ({provider, providers}) y añade el que le pasa el backend justo después, en otro
-- UPDATE de la misma transacción. Por eso crear_perfil ve la cuenta como CLIENTE y
-- este segundo trigger copia rol, negocio y es_dueno cuando app_metadata los trae.
create function public.sincronizar_perfil()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if new.raw_app_meta_data ->> 'rol' is not null then
        update public.perfiles
           set rol        = new.raw_app_meta_data ->> 'rol',
               negocio_id = (new.raw_app_meta_data ->> 'negocio_id')::bigint,
               es_dueno   = coalesce((new.raw_app_meta_data ->> 'es_dueno')::boolean, false),
               disponible = disponible and (new.raw_app_meta_data ->> 'rol') = 'REPARTIDOR'
         where id = new.id;
    end if;
    return new;
end;
$$;

revoke execute on function public.sincronizar_perfil() from public, anon, authenticated;

create trigger al_cambiar_app_metadata
    after update of raw_app_meta_data on auth.users
    for each row
    when (old.raw_app_meta_data is distinct from new.raw_app_meta_data)
    execute function public.sincronizar_perfil();


-- -----------------------------------------------------------------------------
-- 3. Custom Access Token Hook (arquitectura 5.1)
-- Añade al token user_rol, negocio_id y es_dueno leídos de perfiles. Si la
-- cuenta está desactivada, o su negocio suspendido, no se emite el token.
-- -----------------------------------------------------------------------------
create function public.custom_access_token_hook(event jsonb)
returns jsonb
language plpgsql
stable
set search_path = ''
as $$
declare
    claims          jsonb := event -> 'claims';
    v_rol           text;
    v_negocio_id    bigint;
    v_es_dueno      boolean;
    v_activo        boolean;
    v_negocio_ok    boolean;
begin
    select p.rol, p.negocio_id, p.es_dueno, p.activo, coalesce(n.activo, true)
      into v_rol, v_negocio_id, v_es_dueno, v_activo, v_negocio_ok
      from public.perfiles p
      left join public.negocios n on n.id = p.negocio_id
     where p.id = (event ->> 'user_id')::uuid;

    if found and not (v_activo and v_negocio_ok) then
        return jsonb_build_object('error', jsonb_build_object(
            'http_code', 403,
            'message', 'La cuenta está desactivada'));
    end if;

    claims := claims
        || jsonb_build_object('user_rol', v_rol,
                              'negocio_id', v_negocio_id,
                              'es_dueno', coalesce(v_es_dueno, false));

    return jsonb_build_object('claims', claims);
end;
$$;

grant usage on schema public to supabase_auth_admin;
grant execute on function public.custom_access_token_hook(jsonb) to supabase_auth_admin;
revoke execute on function public.custom_access_token_hook(jsonb) from public, anon, authenticated;
grant select on table public.perfiles, public.negocios to supabase_auth_admin;


-- -----------------------------------------------------------------------------
-- 4. Row Level Security
-- El backend se conecta como postgres (BYPASSRLS), así que estas políticas solo
-- afectan a las lecturas directas desde web y apps y a Realtime. No hay
-- políticas de escritura: insertar, modificar o borrar solo lo hace el backend.
-- Los datos del usuario salen del token: auth.uid() y los claims del hook.
-- -----------------------------------------------------------------------------
-- Función auxiliar fuera de public (no se expone en la API de datos). Evita la
-- recursión entre las políticas de pedidos y repartos: lee repartos sin RLS.
create schema privado;
grant usage on schema privado to authenticated;

create function privado.reparto_es_mio(p_pedido_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (select 1 from public.repartos r
                   where r.pedido_id = p_pedido_id and r.repartidor_id = (select auth.uid()));
$$;

revoke execute on function privado.reparto_es_mio(bigint) from public, anon;
grant execute on function privado.reparto_es_mio(bigint) to authenticated;

